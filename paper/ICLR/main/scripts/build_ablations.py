"""只读重算已完成 DeepSeek 四臂消融；不加载模型，不修改实验结果。"""
import json
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ROOT = Path('/data/26xyw/path-consistency-results/math500')
BASE = 'math500_deepseek_v4_flash_b32_c08_rep0_4856d4ef5673'
ARMS = [
    ('SC', '--', '--', BASE, 'sc'),
    ('A', 'BLC', 'On', BASE, 'pc'),
    ('B', 'Uniform', 'On', 'math500_deepseek_selrec_rand_on_rep0_50db3648c31e', 'pc'),
    ('C', 'BLC', 'Off', 'math500_deepseek_selrec_blc_off_rep0_eb9ec59f957a', 'pc'),
    ('D', 'Uniform', 'Off', 'math500_deepseek_selrec_rand_off_rep0_0068abba49a2', 'pc'),
]
summary = []
ids = None
for arm, selector, recovery, tag, method in ARMS:
    manifest = json.loads((ROOT / (tag + '.run.json')).read_text())
    assert manifest['status'] == 'complete', tag
    path = ROOT / f'{tag}_{method}.jsonl'
    raw = path.read_bytes()
    rows = [json.loads(line) for line in raw.splitlines() if line.strip()]
    keys = {r['question_id'] for r in rows}
    assert len(rows) == len(keys) == 490
    if ids is None:
        ids = keys
    assert keys == ids
    eval_correct = sum(bool(r['predictions'][method.upper()]['correct']) for r in rows)
    correct = eval_correct + 10
    n_acc = 500
    tok = sum(r['total_generated_tokens'] for r in rows) / len(rows)
    failed = sum(bool(w.get('rollback_reason')) for r in rows for w in r['windows'])
    summary.append(dict(arm=arm, selector=selector, recovery=recovery, n=n_acc,
                        eval_n=len(rows), eval_correct=eval_correct, correct=correct,
                        accuracy=100*correct/n_acc, tokens=tok,
                        failed_windows=failed, source=path.name,
                        sha256=hashlib.sha256(raw).hexdigest()))
sc = summary[0]['tokens']
lines = ['% Generated by scripts/build_ablations.py; raw grading, n=500 (490 eval + 10 credited).']
for r in summary:
    r['saving'] = 100*(1-r['tokens']/sc)
    delta = r['accuracy'] - summary[0]['accuracy']
    delta_tex = '0.00' if delta == 0 else f'${delta:+.2f}$'
    lines.append(f"{r['arm']} & {r['selector']} & {r['recovery']} & {r['accuracy']:.2f} & "
                 f"{delta_tex} & {r['tokens']:,.0f} & {r['saving']:.1f} \\\\")
(HERE/'tables/ablation_rows.tex').write_text('\n'.join(lines)+'\n')
(HERE/'data/ablation_snapshot.json').write_text(json.dumps(summary,indent=2)+'\n')
for r in summary:
    print(r['arm'],r['n'],r['correct'],round(r['tokens']),round(r['saving'],1),r['failed_windows'])
